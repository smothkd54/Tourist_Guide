def serve_photo(landmark_id: str):
    for ext in (".jpg", ".jpeg", ".png", ".webp"):
        p = PHOTOS_DIR / f"{landmark_id}{ext}"
        if p.exists():
            return send_from_directory(PHOTOS_DIR, p.name)
    return jsonify({"error": "No photo for this landmark"}), 404

