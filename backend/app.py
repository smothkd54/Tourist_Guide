def load_resources():
    """Load model, class names, and landmark metadata into app state."""
    if MODEL_PATH.exists() and not is_lfs_pointer(MODEL_PATH):
        # Served through the TFLite runtime: ~113 MB resident instead of ~392 MB
        # for TensorFlow/Keras, which is what makes two workers fit a 512 MB
        # instance. Predictions are identical (top-1 agreement 1.0 on the test
        # split, max probability difference 0.002).
        app.model = TFLiteModel(MODEL_PATH)
        logger.info("Model loaded from %s (TFLite runtime)", MODEL_PATH)
    elif MODEL_PATH.exists():
        logger.error(
            "Model at %s is a Git LFS pointer — run 'git lfs pull' to "
            "fetch the real file. /predict will return 503 until then.",
            MODEL_PATH,
        )
    else:
        logger.error(
            "Model not found at %s — run train.py first. "
            "/predict will return 503.",
            MODEL_PATH,
        )

    if CLASS_NAMES_PATH.exists():
        app.class_names = json.loads(CLASS_NAMES_PATH.read_text())
    else:
        logger.warning("%s not found. Run train.py first.", CLASS_NAMES_PATH)

    if LANDMARKS_PATH.exists():
        data = json.loads(LANDMARKS_PATH.read_text())
        app.landmarks_by_id = {lm["id"]: lm for lm in data["landmarks"]}
    else:
        raise FileNotFoundError(f"landmarks.json not found at {LANDMARKS_PATH}")

    # Publishing rule: a photo is only served if its author, licence and source
    # are recorded. The audit script verifies that; here the credit is attached
    # to the landmark so both clients can show it next to the photo.
    if PHOTO_ATTRIBUTION_PATH.exists():
        credit = json.loads(PHOTO_ATTRIBUTION_PATH.read_text())
        attached = 0
        for landmark_id, item in credit.items():
            landmark = app.landmarks_by_id.get(landmark_id)
            if landmark is None or not item.get("published"):
                continue
            landmark["photo_attribution"] = {
                "author": item.get("author", ""),
                "license": item.get("license", ""),
                "license_url": item.get("license_url", ""),
                "source_url": item.get("source_url", ""),
            }
            attached += 1
        logger.info("Photo credits attached: %d", attached)
    else:
        logger.warning(
            "%s not found — photos will be served without a credit line. "
            "Run scripts/audit_photo_licenses.py.",
            PHOTO_ATTRIBUTION_PATH,
        )

    logger.info("Classes loaded: %d", len(app.class_names))
    logger.info("Landmarks in DB: %d", len(app.landmarks_by_id))


# Load at import time, not under __main__. gunicorn (Docker) imports this
# module without ever executing the __main__ block — the old placement
# meant production containers served an empty, model-less app (health
# check 503, /landmarks [], /predict 503).
load_resources()


def preprocess_image(image_bytes: bytes) -> np.ndarray:
    """Decode and resize, keeping pixels in [0, 255], then add a batch dim.

    Resizing mirrors `image_dataset_from_directory` exactly (tf.image.resize,
    bilinear, no antialias). Training used that pipeline, and switching to PIL's
    LANCZOS resize changed the top-1 answer on 28% of the test images, so the
    two paths must not diverge silently.

    EfficientNetB0 carries its own Rescaling(1/255) + Normalization layers, so
    the model must receive raw 0-255 values. Scaling here as well made every
    prediction collapse onto a single class.
    """
    img = Image.open(io.BytesIO(image_bytes)).convert("RGB")
    arr = np.asarray(img, dtype=np.float32)
    arr = resize_bilinear(arr, IMG_SIZE)
    return np.expand_dims(arr, axis=0)


def mask_unvalidated(probs: np.ndarray, class_names: list[str]) -> np.ndarray:
    """Zero the classes we never validated, then renormalise what is left.

    This keeps confidence comparable: it is the probability of the answer
    *given* that the building is one the model can actually recognise.
    """
    if not UNVALIDATED_CLASSES:
        return probs
    keep = np.array([name not in UNVALIDATED_CLASSES for name in class_names])
    if keep.all():
        return probs
    masked = np.where(keep, probs, 0.0)
    total = masked.sum()
    return masked / total if total > 0 else probs


def decode_base64_image(b64_string: str) -> bytes:
    """Handle both raw base64 and data-URI prefixed strings."""
    if "," in b64_string:
        b64_string = b64_string.split(",", 1)[1]
    return base64.b64decode(b64_string)


def haversine_m(lat1, lon1, lat2, lon2):
    import math
    R = 6_371_000
    phi1, phi2 = math.radians(lat1), math.radians(lat2)
    dphi = math.radians(lat2 - lat1)
    dlambda = math.radians(lon2 - lon1)
    a = math.sin(dphi / 2) ** 2 + math.cos(phi1) * math.cos(phi2) * math.sin(dlambda / 2) ** 2
    return 2 * R * math.asin(math.sqrt(a))


